# Pure, independently written in-process Basic generation. No CAD is activated.
. (Join-Path $PSScriptRoot 'basic.ps1')
function New-StudioPADSModelBasic($Job,$Item,[string]$PrivateExe,[string]$Template,[string]$Board,[string]$Library,[string]$Netlist,[string]$Record) {
 $q={param($v) BasicString ([string]$v)}
 $lines=New-Object Collections.Generic.List[string]
 $lines.Add('Declare Sub Sleep Lib "kernel32" (ByVal milliseconds As Long)')
 $lines.Add('Declare Function GetWindowThreadProcessId Lib "user32" (ByVal window As Long, ByRef process As Long) As Long')
 $lines.Add('Declare Function GetCurrentProcessId Lib "kernel32" () As Long')
 $lines.Add('Sub Main')
 $lines.Add(' Dim channel As Integer, lib As Object, doc As Object, component As Object, imported As Object')
 $lines.Add(' Dim bridge As Object, sys As Object, maps As Object, nativeComponent As Object, box As Object, n As Integer, ready As Boolean, failure As String, nativePID As Long')
 $lines.Add(' On Error GoTo Failed')
 $lines.Add((' If Application.GetConfigParamString("PackageStudioModels", "Nonce", "") <> '+(&$q $Job.nonce)+' Then Err.Raise 2301, , "Private INI guard failed"'))
 $lines.Add((' If LCase(Application.FullName) <> LCase('+(&$q $PrivateExe)+') Then Err.Raise 2302, , "Unexpected process executable"'))
 $lines.Add((' If LCase(Application.GetConfigParamString("directories", "ReuseDir", "")) <> LCase('+(&$q $Job.reuse)+') Then Err.Raise 2303, , "Private Reuse guard failed"'))
 $lines.Add(' channel = FreeFile')
 $lines.Add((' Open '+(&$q $Record)+' For Output As #channel'))
 $lines.Add(' Print #channel, "PID|" & CStr(GetCurrentProcessId())')
 $lines.Add((' Set lib = Application.CreateLibrary('+(&$q $Library)+', False)'))
 $lines.Add(' If lib Is Nothing Then Err.Raise 2304, , "Cannot create private fixture library"')
 $lines.Add(' If LCase(lib.FullName) <> LCase('+(&$q $Library)+') And LCase(lib.FullName) <> LCase('+(&$q ($Library+'.pt9'))+') Then Err.Raise 2305, , "Unexpected fixture library"')
 $lines.Add((' Set imported = lib.ImportLibraryItems2('+(&$q $Job.pcb)+', 2)'))
 $lines.Add((' Set imported = lib.ImportLibraryItems2('+(&$q $Job.partTypes)+', 2)'))
 $lines.Add((' Set doc = Application.OpenDocument('+(&$q $Template)+')'))
 $lines.Add((' If LCase(doc.FullName) <> LCase('+(&$q $Template)+') Or doc.Components.Count <> 0 Then Err.Raise 2306, , "Selected default PCB is not an empty private fixture"'))
 $lines.Add((' doc.SaveAs '+(&$q $Board)))
 $lines.Add((' If LCase(doc.FullName) <> LCase('+(&$q $Board)+') Then Err.Raise 2307, , "Fixture SaveAs failed"'))
 $lines.Add((' If doc.ImportNetList('+(&$q $Netlist)+') = 0 Then Err.Raise 2308, , "Fixture netlist import failed"'))
 $lines.Add(' If doc.Components.Count <> 1 Then Err.Raise 2309, , "Fixture component count mismatch"')
 $lines.Add(' Set component = doc.Components.Item(1)')
 $lines.Add((' If component.Name <> "PT1" Or component.PartType <> '+(&$q $Item.entry)+' Or component.Decal <> '+(&$q $Item.decal)+' Then Err.Raise 2310, , "Fixture part/decal mismatch"'))
 $lines.Add(' doc.Preference("DRC") = ppcbDRCOff')
 $lines.Add(' doc.Preference("Nudge") = ppcbNudgeOff')
 $lines.Add(' component.Glued = False')
 $lines.Add(' component.Move 0, 0')
 $lines.Add(' component.Orientation = 0')
 $lines.Add(' If Abs(component.PositionX) > 0.000001 Or Abs(component.PositionY) > 0.000001 Or Abs(component.Orientation) > 0.000001 Then Err.Raise 2311, , "Fixture must use origin and zero rotation"')
 $lines.Add(' doc.Save')
 $lines.Add(' Application.Visible = True')
 $lines.Add(' Set bridge = Application.MGCPCBApplication')
 $lines.Add(' GetWindowThreadProcessId bridge.Gui.HWND, nativePID')
 $lines.Add(' If nativePID = 0 Or nativePID <> GetCurrentProcessId() Then Err.Raise 2317, , "System3D bridge belongs to a different process"')
 $lines.Add(' Print #channel, "VERSION|" & bridge.Version')
 $lines.Add(' Set sys = bridge.ActiveDocument.System3D')
 $lines.Add(' ready = False')
 $lines.Add(' If Not sys Is Nothing Then ready = sys.IsReady()')
 $lines.Add(' If Not ready Then Application.ProcessCommand 40300')
 $lines.Add(' For n = 1 To 60')
 $lines.Add('  Set sys = bridge.ActiveDocument.System3D')
 $lines.Add('  If Not sys Is Nothing Then')
 $lines.Add('   If sys.IsReady() Then ready = True: Exit For')
 $lines.Add('  End If')
 $lines.Add('  Sleep 500')
 $lines.Add(' Next n')
 $lines.Add(' If Not ready Then Err.Raise 2312, , "System3D is not ready; selected SDK or license is incompatible"')
 $lines.Add((' If LCase(Application.ActiveDocument.FullName) <> LCase('+(&$q $Board)+') Then Err.Raise 2318, , "Active fixture changed before model access"'))
 $lines.Add(' Set maps = sys.Mappings()')
 if($Job.phase -eq 'convert' -and -not $Item.existing) {
  $lines.Add((' If maps.IsMapped('+(&$q $Item.entry)+', '+(&$q $Item.decal)+') Then Err.Raise 2313, , "Existing mapping cannot be overwritten"'))
  $lines.Add((' maps.ImportModel '+(&$q $Item.step)+', '+(&$q $Item.entry)+', '+(&$q $Item.decal)))
  $lines.Add((' If Not maps.IsMapped('+(&$q $Item.entry)+', '+(&$q $Item.decal)+') Or Not maps.IsLocallyMapped('+(&$q $Item.entry)+', '+(&$q $Item.decal)+') Then Err.Raise 2314, , "ImportModel did not create a local mapping"'))
  $lines.Add((' maps.ExportModels '+(&$q $Job.reuse)))
 }
 $lines.Add((' If Not maps.IsMapped('+(&$q $Item.entry)+', '+(&$q $Item.decal)+') Then Err.Raise 2315, , "Saved mapping is missing"'))
 $lines.Add((' Print #channel, "MODEL|" & maps.GetModelName('+(&$q $Item.entry)+', '+(&$q $Item.decal)+')'))
 $lines.Add((' Print #channel, "LOCAL|" & CStr(maps.IsLocallyMapped('+(&$q $Item.entry)+', '+(&$q $Item.decal)+'))'))
 $lines.Add(' Set nativeComponent = bridge.ActiveDocument.FindComponent("PT1")')
 $lines.Add(' Set box = sys.Model.BoundingBox(2, nativeComponent.UniqueId)')
 $lines.Add(' If Not box.IsValid() Then Err.Raise 2316, , "Native model bounding box is invalid"')
 $lines.Add(' Print #channel, "BBOX|" & CStr(box.MinX(4)) & "|" & CStr(box.MinY(4)) & "|" & CStr(box.MinZ(4)) & "|" & CStr(box.MaxX(4)) & "|" & CStr(box.MaxY(4)) & "|" & CStr(box.MaxZ(4))')
 $lines.Add((' If LCase(doc.FullName) <> LCase('+(&$q $Board)+') Then Err.Raise 2319, , "Private fixture changed before save"'))
 $lines.Add(' doc.Save')
 $lines.Add((' Print #channel, '+(&$q ('DONE|'+$Job.nonce))))
 $lines.Add(' Close #channel')
 $lines.Add(' Exit Sub')
 $lines.Add('Failed:')
 $lines.Add(' failure = Err.Description')
 $lines.Add(' On Error Resume Next')
 $lines.Add(' If channel = 0 Then channel = FreeFile')
 $lines.Add((' Open '+(&$q $Record)+' For Append As #channel'))
 $lines.Add(' Print #channel, "ERROR|" & failure')
 $lines.Add(' Close #channel')
 $lines.Add('End Sub')
 return ($lines -join "`r`n")+"`r`n"
}
