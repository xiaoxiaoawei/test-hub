package core

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"math"
	"strconv"
	"strings"
)

func skillString(s string) string    { return strconv.Quote(strings.ReplaceAll(s, "\x00", "")) }
func skillPoint(x, y float64) string { return "list(" + f(x) + " " + f(-y) + ")" }

func renderCadenceAllegro(p Part, entry string) (string, CadenceAllegroJob, []string, error) {
	job := CadenceAllegroJob{Entry: entry, Directory: "allegro/" + entry, Script: "allegro/" + entry + "/build.scr", CompletionMarker: "allegro/" + entry + "/allegro-complete.txt", ExpectedFiles: []string{}}
	warnings := []string{"Allegro 脚本使用 mm；阻焊/锡膏默认与焊盘同轮廓，需结合目标工艺规则复核。", "Allegro PLACE_BOUND_TOP 使用源封装边界的包围矩形，请核对机械装配间距。"}
	var b strings.Builder
	b.WriteString("; Independently generated by Package Studio. Execute only in a new batch session.\nprocedure(psBuildPackage()\n  let((pads drill ps pin orient pintext report)\n")
	for _, api := range []string{"axlOpenDesign", "axlDBCreatePadStack", "axlDBCreatePin", "axlPadstackToDisk", "axlSaveDesign", "axlCompileSymbol"} {
		fmt.Fprintf(&b, "    unless(fboundp('%s) error(\"Required Allegro API is unavailable: %s\"))\n", api, api)
	}
	fmt.Fprintf(&b, "    unless(axlOpenDesign(?design %s ?mode \"n\" ?noMru t) error(\"Could not create a fresh package drawing\"))\n", skillString(entry+".dra"))
	b.WriteString("    axlSetSymbolType(\"package\")\n    axlDBChangeDesignUnits(\"millimeters\" 4)\n    axlSetVariable(\"padpath\" \".\")\n    axlSetVariable(\"psmpath\" \".\")\n")
	bounds := p.Footprint.Bounds
	if bounds.Width <= 0 || bounds.Height <= 0 {
		return "", job, warnings, fmt.Errorf("封装边界无效")
	}
	fmt.Fprintf(&b, "    axlDBChangeDesignExtents(list(%s %s))\n", skillPoint(math.Min(0, bounds.X)-10, math.Max(0, bounds.Y+bounds.Height)+10), skillPoint(math.Max(0, bounds.X+bounds.Width)+10, math.Min(0, bounds.Y)-10))
	defined := map[string]string{}
	for _, pad := range p.Footprint.Pads {
		if pad.Shape == "custom" || len(pad.Points) > 0 {
			return "", job, warnings, fmt.Errorf("焊盘 %s 为自定义多边形；当前 Allegro 生成器尚不支持，不会近似替换", pad.Number)
		}
		if pad.DrillWidth > pad.Drill {
			return "", job, warnings, fmt.Errorf("焊盘 %s 为槽孔；当前 Allegro 生成器尚未验证槽孔 API", pad.Number)
		}
		if pad.Drill < 0 {
			return "", job, warnings, fmt.Errorf("焊盘 %s 孔径无效", pad.Number)
		}
		geometry := struct {
			W, H, D            float64
			Shape, Type, Layer string
		}{pad.Width, pad.Height, pad.Drill, pad.Shape, pad.Type, pad.Layer}
		data, _ := json.Marshal(geometry)
		key := string(data)
		name, exists := defined[key]
		if !exists {
			hash := sha256.Sum256(data)
			name = "ps_" + hex.EncodeToString(hash[:6])
			defined[key] = name
			code, w, err := renderCadencePadStack(pad, name)
			if err != nil {
				return "", job, warnings, err
			}
			warnings = append(warnings, w...)
			b.WriteString(code)
			job.ExpectedFiles = append(job.ExpectedFiles, job.Directory+"/"+name+".pad")
		}
		b.WriteString("    orient = make_axlTextOrientation(?textBlock \"1\" ?justify \"center\")\n")
		if pad.Number != "" {
			fmt.Fprintf(&b, "    pintext = make_axlPinText(?number %s ?offset list(0.0 0.0) ?text orient)\n", skillString(pad.Number))
		} else {
			b.WriteString("    pintext = nil\n")
		}
		fmt.Fprintf(&b, "    unless(axlLoadPadstack(%s) error(\"Could not reload the generated padstack\"))\n", skillString(name))
		fmt.Fprintf(&b, "    pin = axlDBCreatePin(%s %s pintext %s)\n    unless(pin error(\"Could not create a package pin\"))\n", skillString(name), skillPoint(pad.X, pad.Y), f(-pad.Rotation))
	}
	for _, line := range p.Footprint.Lines {
		layer, err := cadenceLayer(line.Layer)
		if err != nil {
			return "", job, warnings, err
		}
		fmt.Fprintf(&b, "    unless(axlDBCreateLine(list(%s %s) %s %s) error(\"Line creation failed\"))\n", skillPoint(line.X1, line.Y1), skillPoint(line.X2, line.Y2), f(math.Max(.001, line.Width)), skillString(layer))
	}
	for _, circle := range p.Footprint.Circles {
		layer, err := cadenceLayer(circle.Layer)
		if err != nil {
			return "", job, warnings, err
		}
		if circle.Radius <= 0 {
			return "", job, warnings, fmt.Errorf("圆形半径无效")
		}
		fmt.Fprintf(&b, "    unless(axlDBCreateCircle(list(%s %s) %s %s) error(\"Circle creation failed\"))\n", skillPoint(circle.X, circle.Y), f(circle.Radius), f(math.Max(.001, circle.Width)), skillString(layer))
	}
	for _, polygon := range p.Footprint.Polygons {
		if len(polygon.Points) < 3 {
			return "", job, warnings, fmt.Errorf("封装多边形少于3个顶点")
		}
		layer, err := cadenceLayer(polygon.Layer)
		if err != nil {
			return "", job, warnings, err
		}
		var pts strings.Builder
		pts.WriteString("list(")
		for _, v := range polygon.Points {
			pts.WriteString(skillPoint(v.X, v.Y) + " ")
		}
		pts.WriteString(skillPoint(polygon.Points[0].X, polygon.Points[0].Y) + ")")
		if polygon.Fill {
			fmt.Fprintf(&b, "    unless(axlDBCreateShape(axlPathStart(%s) t %s) error(\"Filled polygon creation failed\"))\n", pts.String(), skillString(layer))
		} else {
			fmt.Fprintf(&b, "    unless(axlDBCreateLine(%s %s %s) error(\"Polygon outline creation failed\"))\n", pts.String(), f(math.Max(.001, polygon.Width)), skillString(layer))
		}
	}
	for _, text := range p.Footprint.Texts {
		if text.Text == "" {
			continue
		}
		layer, err := cadenceLayer(text.Layer)
		if err != nil {
			return "", job, warnings, err
		}
		fmt.Fprintf(&b, "    orient = make_axlTextOrientation(?textBlock \"1\" ?rotation %s ?justify \"left\")\n    unless(axlDBCreateText(%s %s orient %s) error(\"Text creation failed\"))\n", f(-text.Rotation), skillString(text.Text), skillPoint(text.X, text.Y), skillString(layer))
		warnings = append(warnings, "Allegro 普通文字使用目标 drawing 的 Text Block 1；源字号尚未自动映射。")
	}
	fmt.Fprintf(&b, "    unless(axlDBCreateRectangle(list(%s %s) t \"PACKAGE GEOMETRY/PLACE_BOUND_TOP\") error(\"Placement bound creation failed\"))\n", skillPoint(bounds.X, bounds.Y+bounds.Height), skillPoint(bounds.X+bounds.Width, bounds.Y))
	b.WriteString("    orient = make_axlTextOrientation(?textBlock \"1\" ?justify \"center\")\n")
	fmt.Fprintf(&b, "    unless(axlDBCreateText(\"REF**\" %s orient \"REF DES/SILKSCREEN_TOP\") error(\"Reference text creation failed\"))\n", skillPoint(0, bounds.Y-1))
	fmt.Fprintf(&b, "    unless(axlSaveDesign(?design %s ?noConfirm t ?noMru t) error(\"DRA save failed\"))\n", skillString(entry+".dra"))
	fmt.Fprintf(&b, "    unless(axlCompileSymbol(?symbol %s ?silent t ?silentOnOverwrite t) error(\"Package symbol compile failed\"))\n", skillString(entry+".psm"))
	b.WriteString("    report = outfile(\"allegro-complete.txt\" \"w\")\n    unless(report error(\"Cannot write completion marker\"))\n    fprintf(report \"Package Studio generated package; engine=%L\\n\" axlVersion('version))\n    close(report)\n    t\n  )\n)\n")
	job.ExpectedFiles = append(job.ExpectedFiles, job.Directory+"/"+entry+".dra", job.Directory+"/"+entry+".psm")
	return b.String(), job, uniqueCadenceWarnings(warnings), nil
}

func renderCadencePadStack(p Pad, name string) (string, []string, error) {
	var b strings.Builder
	warnings := []string{}
	through := p.Drill > 0
	layers := []string{"TOP", "SOLDERMASK_TOP", "PASTEMASK_TOP"}
	if through {
		layers = []string{"TOP", "DEFAULT INTERNAL", "BOTTOM", "SOLDERMASK_TOP", "SOLDERMASK_BOTTOM"}
		warnings = append(warnings, "通孔焊盘尚未生成内电层热焊盘/反焊盘，需依据实际叠层和间距规则复核。")
	}
	if !through && p.Layer == "B.Cu" {
		layers = []string{"BOTTOM", "SOLDERMASK_BOTTOM", "PASTEMASK_BOTTOM"}
	}
	figure := ""
	options := ""
	switch p.Shape {
	case "rect":
		figure = "RECTANGLE"
	case "roundrect":
		figure = "ROUNDED_RECTANGLE"
		options = " ?corners \"UL-UR-LR-LL\" ?radius " + f(math.Min(p.Width, p.Height)*.15)
		warnings = append(warnings, "圆角矩形焊盘半径按短边15%生成，输入模型未提供显式半径，请核对原始封装。")
	case "circle":
		if math.Abs(p.Width-p.Height) > .0001 {
			return "", warnings, fmt.Errorf("非等径圆形焊盘 %s 不可无损导出", p.Number)
		}
		figure = "CIRCLE"
	case "oval":
		if p.Width >= p.Height {
			figure = "OBLONG_X"
		} else {
			figure = "OBLONG_Y"
		}
	default:
		return "", warnings, fmt.Errorf("不支持的 Allegro 焊盘形状：%s", p.Shape)
	}
	b.WriteString("    pads = nil\n")
	for _, layer := range layers {
		fmt.Fprintf(&b, "    ps = make_axlPadStackPad(?layer %s ?type 'REGULAR ?figure '%s ?figureSize list(%s %s)%s)\n    unless(ps error(\"Pad figure creation failed\"))\n    pads = cons(ps pads)\n", skillString(layer), figure, f(p.Width), f(p.Height), options)
	}
	if through {
		plating := "PLATED"
		if p.Type == "np_thru_hole" {
			plating = "NON_PLATED"
		}
		fmt.Fprintf(&b, "    drill = make_axlPadStackDrill(?drillDiameter %s ?figure 'NULL ?figureSize list(%s %s) ?plating '%s)\n", f(p.Drill), f(p.Drill), f(p.Drill), plating)
	} else {
		b.WriteString("    drill = nil\n")
	}
	fmt.Fprintf(&b, "    unless(axlDBCreatePadStack(%s drill reverse(pads) t) error(\"Padstack creation failed\"))\n    unless(axlPadstackToDisk(%s %s) error(\"Padstack save failed\"))\n", skillString(name), skillString(name), skillString(name+".pad"))
	return b.String(), warnings, nil
}

func cadenceLayer(layer string) (string, error) {
	out := map[string]string{"F.Cu": "ETCH/TOP", "B.Cu": "ETCH/BOTTOM", "F.SilkS": "PACKAGE GEOMETRY/SILKSCREEN_TOP", "B.SilkS": "PACKAGE GEOMETRY/SILKSCREEN_BOTTOM", "F.Fab": "PACKAGE GEOMETRY/ASSEMBLY_TOP", "B.Fab": "PACKAGE GEOMETRY/ASSEMBLY_BOTTOM", "F.CrtYd": "PACKAGE GEOMETRY/PLACE_BOUND_TOP", "B.CrtYd": "PACKAGE GEOMETRY/PLACE_BOUND_BOTTOM", "F.Mask": "PACKAGE GEOMETRY/SOLDERMASK_TOP", "B.Mask": "PACKAGE GEOMETRY/SOLDERMASK_BOTTOM", "F.Paste": "PACKAGE GEOMETRY/PASTEMASK_TOP", "B.Paste": "PACKAGE GEOMETRY/PASTEMASK_BOTTOM", "Dwgs.User": "PACKAGE GEOMETRY/ASSEMBLY_TOP", "Edge.Cuts": "PACKAGE GEOMETRY/ASSEMBLY_TOP"}[layer]
	if out == "" {
		return "", fmt.Errorf("不支持的 Allegro 图层：%s", layer)
	}
	return out, nil
}
